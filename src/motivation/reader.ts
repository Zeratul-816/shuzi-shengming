/**
 * 读他这一句话 —— 纯规则，不调模型，0 成本，可单测。
 *
 * ── 为什么需要它 ─────────────────────────────────────────
 *   v2 的被动回复路径只有**一个**意图：`reply`，而且语气只有一档
 *   （`needs.rest > 0.6 ? "有点省力" : "自然"`）。也就是说整个系统里
 *   95% 的轮次用的都是同一张动机卡 —— 人格的全部差异只发生在"主动发言"
 *   那 5% 里。这解释了一个现象：设定写得再细，聊起来还是同一个人。
 *
 *   v3 让被动路径也选意图。选意图需要知道"他刚才那句话是在干什么"，
 *   而这件事**必须由规则做**（铁律 #1：动机不交给 LLM）。所以这里用
 *   正则做一次粗分类，输出几个布尔位。粗就够了：它只需要区分
 *   "他在关心我" / "他在问我感受" / "他在夸我" / "他在催我"。
 *
 * ── 为什么不交给表达层自己判断 ───────────────────────────
 *   如果让表达层"看情况决定要不要拒绝被关心"，它会在被夸的时候拒绝关心、
 *   在被关心的时候倒苦水 —— 因为那是语言模型觉得"更好看"的选择。
 *   规则引擎的粗糙在这里是**优点**：它稳定，而且你能调。
 */
import type { UserRead } from "../shared/types.ts";

/**
 * 关心/担心她的状态。
 *
 * ★ 这一条必须**分清"你在累"和"我在累"**。
 *   第一版是一串「累不累|辛苦了|还好吗…」，真机第一轮就露馅：
 *   用户说"你还撑得住吗？听起来挺累的"，一个都没命中 —— 而
 *   "我今天特别累"反而会被"累"字误判成他在关心她。
 *   所以改成"你 + 就近的疲劳/关心词"这种带指向的匹配。
 */
const CARING = new RegExp(
  [
    "你[^。！？，,]{0,6}(累|撑|还好|没事|辛苦|休息|歇|勉强|硬撑|逞强|习惯|吃了吗|睡)",
    "(辛苦|心疼|担心|挂念|惦记)(你|了)",
    // 注意这个 lookbehind：「特别累」「区别很大」不是劝人别累；
    // 没有它，"我今天特别累"会被当成他在关心她 —— 方向正好反了。
    "(?<![特区级类别性])别(太)?(累|勉强|硬撑|逞强)",
    "(不要|不用|别再)(太)?(累|勉强|硬撑|逞强)",
    "(累不累|撑得住|顶得住|还好吧|没事吧|要不要休息|歇一会|歇会儿|放松点|有我呢|抱抱|别怕)",
  ].join("|"),
);

/**
 * 问她的感受（不是问观点）。
 * 中间允许几个字：「你自己开心吗」「你现在感觉怎么样」「你是不是很累」。
 * 刻意**不含**「你觉得」—— 那是问意见，不该触发回避。
 */
const ASK_FEELING =
  /你(自己|现在|最近|心里|是不是|会不会|有没有|觉得|感觉)?(开心|高兴|难过|难受|害怕|怕|孤单|寂寞|累|困|委屈|烦|失落|满意|在想什么|愿意|想不想)/;

/** 问观点/意见（不是感受，不该触发回避） */
const ASK_OPINION = /(你觉得|你怎么看|你认为|你说呢|有没有必要|怎么办|该不该)/;

/** 夸她能干/夸她好 */
const PRAISING = /(厉害|佩服|做得好|很棒|真好|不错|你行|真行|优秀|了不起|可靠|多亏了?你|帮了大忙|机灵|聪明)/;

/** 命令/催 */
const DEMANDING = /(你必须|快去|赶紧|马上|立刻|现在就|给我去|别废话)/;

/** 强硬否定（她的动机被顶回来过，这里只是识别语气） */
const PUSHY = /(不行|没用|别说了|算了吧|不用了|不需要|没这个必要|少来|别扯|随便你)/;

/** 紧急 */
const URGENT = /(急|救命|快点|出事了|来不及|马上要)/;

export function readUserTurn(text: string): UserRead {
  const t = text ?? "";
  const questions = (t.match(/[?？]/g) ?? []).length + (/(吗|呢|吧)$/.test(t.trim()) ? 1 : 0);
  return {
    length: t.length,
    questions,
    caring: CARING.test(t),
    askingFeeling: ASK_FEELING.test(t),
    askingOpinion: ASK_OPINION.test(t),
    praising: PRAISING.test(t),
    demanding: DEMANDING.test(t),
    pushy: PUSHY.test(t),
    urgent: URGENT.test(t),
    empty: t.trim().length === 0,
  };
}
